import { describe, expect, it } from "vitest";

import { parseAnchorUntilTimestamp } from "../../src/orchestrator/anchor-date.js";

describe("parseAnchorUntilTimestamp", () => {
  it.each([
    ["2026-06-11T11:30:00.000Z", "2026-06-11T11:30:00.000Z"],
    ["2026-06-11T07:30:00-04:00", "2026-06-11T11:30:00.000Z"],
    ["2026-06-11T16:30:00+05:00", "2026-06-11T11:30:00.000Z"],
    ["2026-06-11T11:30:00.1Z", "2026-06-11T11:30:00.100Z"],
    ["2026-06-11T11:30:00.12Z", "2026-06-11T11:30:00.120Z"],
    ["2026-06-11T11:30:00.123Z", "2026-06-11T11:30:00.123Z"],
    ["2028-02-29T00:00:00Z", "2028-02-29T00:00:00.000Z"],
    ["2026-12-31T23:59:59+23:59", "2026-12-31T00:00:59.000Z"],
    [" 2026-06-11T11:30:00Z ", "2026-06-11T11:30:00.000Z"],
  ])("normalizes %s", (input, expected) => {
    expect(parseAnchorUntilTimestamp(input)).toBe(expected);
  });

  it.each([
    "2026-06-11",
    "2026-06-11T11:30:00",
    "June 11 2026 11:30 UTC",
    "2026-02-29T11:30:00Z",
    "2026-02-30T11:30:00Z",
    "2026-00-11T11:30:00Z",
    "2026-13-11T11:30:00Z",
    "2026-06-11T24:00:00Z",
    "2026-06-11T11:60:00Z",
    "2026-06-11T11:30:60Z",
    "2026-06-11T11:30:00+24:00",
    "2026-06-11T11:30:00+00:60",
    "2026-06-11T11:30:00.1234Z",
  ])("rejects %s", (input) => {
    expect(parseAnchorUntilTimestamp(input)).toBeNull();
  });
});
